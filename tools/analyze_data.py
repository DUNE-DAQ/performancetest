    data = utils.search_hdf5_data(test_args["data_path"], test_args["dunedaq_version"])
    print(data)

    for d in data:
        if data[d]:
            data[d] = times.slice_time_range(files.read_hdf5(data[d]), tr)

    if test_args["plot_path"]:
        out = test_args["plot_path"] + "analysis/"
    else:
        out = utils.make_plot_dir(test_args) + "analysis/"
    os.makedirs(out, exist_ok = True)

    ro_apps = get_readout_application_name(data, test_args["host"])

    pinning_file = shell.search_data_file("cpupin-all-running", test_args["data_path"])
    if len(pinning_file) == 0:
        pinning_file = None
    else:
        pinning_file = files.read_json(pinning_file[0])

    if pinning_file:
        pinning_file = parse_pinning_file(pinning_file, test_args["host"], ro_apps)


    if ("crp" in test_args["data_source"].lower()) or ("np02" in test_args["data_source"].lower()):
        readout_plane = ReadoutPlane.CRP
    elif ("apa" in test_args["data_source"].lower()) or ("np04" in test_args["data_source"].lower()):
        readout_plane = ReadoutPlane.APA
    else:
        print(f"cannot infer readout plane type based on data_source: {test_args['data_source']}, default to APA.")
        readout_plane = ReadoutPlane.APA

    if len(test_args["host"]) == 1:
        def_name = test_args["host"][0].replace("-", "")
    else:
        def_name = None
    intel_pcm = utils.search_dict(data, "A_CvwTCWk")
    simplify_dict_name(intel_pcm, def_name)
    uprof = utils.search_dict(data, "uprof-pcm")
    simplify_dict_name(uprof, def_name)
    node_exporter = utils.search_dict(data, "node-exporter")
    simplify_dict_name(node_exporter, def_name)

    for k, v in intel_pcm.items():
        if v is not None:
            process_cache_info(v, None, out, test_args, k.replace("srv", "-srv-"))

    for k, v in uprof.items():
        if v is not None:
            process_cache_info(None, v, out, test_args, k.replace("srv", "-srv-"))

    for k, v in node_exporter.items():
        h = k.replace("srv", "-srv-")
        if pinning_file:
            pf = pinning_file.get(k)
        else:
            pf = None
        process_cpu_info(v, out, test_args, h, hw_info[h], pinning_file = pf)

        process_disk_info(v, out, readout_plane, test_args, h)

        process_network_info(v, out, test_args, h)

    for h in test_args["host"]:
        k = h.replace("-", "")
        if k not in node_exporter:
            print(f"Warning: no node exporter data captured for {h}")
            continue
        process_memory_info(node_exporter.get(k), intel_pcm.get(k), uprof.get(k), out, hw_info[h], test_args, h)

    process_frontend_info(data["frontend_ethernet"], out, readout_plane, test_args)

    tph = data["tp_handlers"]
    if tph is None: tph = {} # tp_handler dashboard did not exist in old grafana format
    process_tp_info(data["trigger_primitives"] | tph, out, readout_plane, test_args)

    for d, func in zip(["readout", "overview", "overview"], [process_readout_info, process_daq_overview_info, process_message_report]):
        if d not in expected_dashboards: continue
        func(data[d], out, test_args)
    return



def process_frontend_info(data : dict[pd.DataFrame], out : str, readout_plane : ReadoutPlane, test_args : dict):
    """ Process frontend readout information and make plots.

    Args:
        data (dict[pd.DataFrame]): Node exporter data.
        out (str): Output file diretory.
        readout_plane (ReadoutPlane): The readout plane tested with.
        test_args (dict): Test configuration arguments.
    """
    rx_throughput = list(utils.search_dict(data, "Throughput").values())[0] # bytes recevied from each queue in a readout application
    if rx_throughput.empty:
        print("Warning: no frontend ethernet data was found!")
        return
    start_time = int(rx_throughput.index[0])
    UDPQueue = namedtuple("UDPQueue", ["element", "subelement", "queue"])

    dict_cols = {}
    old_fmt = False
    for c in rx_throughput.columns:
        literal = ast.literal_eval(c)
        if "application" in literal: # this is older style of frontend data, so it needs to be reformatted
            literal["element"] = literal.pop("application")
            literal["subelement"] = None # did not exist in old format
            old_fmt = True
        dict_cols[c] = UDPQueue(**literal)
    rx_throughput = rx_throughput.rename(columns = dict_cols)

    rp = readout_plane_values[readout_plane]

    adc_data_stream_rate_per_ch = rp.adc_size * rp.adc_sampling_rate / 8 # B/s

    max_rate_per_stream = rp.channels_per_queue * adc_data_stream_rate_per_ch # B/s

    unique_element = np.unique([c.element for c in rx_throughput.columns])
    if old_fmt:
        app_names = [i.element for i in dict_cols.values()]
    else:
        app_names = [i.split("-")[1] for i in unique_element]


    rx_throughput_elems = {}
    queue_nums = []
    for elem in unique_element:
        app_queues = [rx_throughput[c] for c in rx_throughput.columns if c.element == elem]
        queue_nums.append(len(app_queues))
        rx_throughput_elems[elem] = sum(app_queues)

    rx_throughput_elems = pd.DataFrame(rx_throughput_elems)

    if len(queue_nums) > 1:
        print("Warning: rx queue number for applications differ, will use the first to calculate expected rate.")
    n_queues_per_elem = queue_nums[0]

    # input + missed = total
    input_packets = sum_over_app(data["Input Packets"], app_names)
    input_missed_packets = sum_over_app(data["Input Missed Packets"], app_names)
    rx_dropped_packets = sum_over_app(data["RX Dropped Packets"], app_names)
    total_packets = input_packets + input_missed_packets

    with plotting.PlotBook(out + "fe_plots") as book:

        plotting.plot(times.relative_time(rx_throughput_elems)/10, rx_throughput_elems, rx_throughput_elems.columns, "Time (s)", "RX throughput", autofmt = "B/s")
        # plotting.hline(max_rate_per_stream * n_queues_per_elem, "Acceptance data input", autofmt = "B/s", linestyle = "--")
        plotting.plt.legend(fontsize="x-small")
        plotting.add_metadata(test_args, start_time)
        book.save()

        if len(input_missed_packets) > 0:
            plotting.plot(times.relative_time(input_missed_packets)/10, 100*input_missed_packets/total_packets, input_missed_packets.columns, "Time (s)", "Missed Packets (%)")
            plotting.add_metadata(test_args, start_time)
            book.save()

            plotting.plot(times.relative_time(input_missed_packets)/10, 100*rx_dropped_packets/total_packets, rx_dropped_packets.columns, "Time (s)", "Dropped Packets (%)")
            plotting.add_metadata(test_args, start_time)
            book.save()
        else:
            print("Note: no missing/dropped packe info was found.")

        plotting.plot(times.relative_time(rx_throughput)/10, rx_throughput, None, "Time (s)", "RX throughput", autofmt = "B/s")
        # plotting.hline(max_rate_per_stream, "Acceptance data input", autofmt = "B/s", linestyle = "--")
        plotting.plt.legend(fontsize="x-small")
        plotting.add_metadata(test_args, start_time)
        book.save()

        total_errors = {k : v.sum(axis=0) for k,v in utils.search_dict(data, "(?=.*RX)(?=.*Error)(?!.*Queue)").items()}
        label =  [f"{readout_plane.name} {i}" for i, _ in enumerate(list(total_errors.values())[0].index)]
        for k, v in total_errors.items():
            plotting.bar(label, v.values, None, k, bar_label = True)
            plotting.plt.ylim(0)
            plotting.add_metadata(test_args, start_time, False)
            book.save()

        total_dropped_frames = {f"{readout_plane.name} {i}" : v.sum().sum() for i, v in enumerate(utils.search_dict(data, "RX Dropped Frames").values())}
        plotting.bar(list(total_dropped_frames.keys()), list(total_dropped_frames.values()), None, "RX Dropped Frames", bar_label = True)
        plotting.plt.ylim(0)
        plotting.add_metadata(test_args, start_time)
        book.save()

        total_errors_dlh = {}
        for k, v in utils.search_dict(data, "Total errors").items():
            key = [i for i in app_names if i in k][0]
            total_errors_dlh[key] = v.sum().sum()
        plotting.bar(list(total_errors_dlh.keys()), list(total_errors_dlh.values()), None, "Errors from DLH", bar_label = True)
        plotting.plt.ylim(0)
        plotting.add_metadata(test_args, start_time)
        book.save()
    return


